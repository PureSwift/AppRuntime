// swift-tools-version:6.4
import Foundation
import PackageDescription

/// A host built the way a platform host is: AppRuntime without the
/// `GuestExports` trait, linked with an app's library.
///
/// The environment picks the library; each test run links one, since every
/// library defines `rt_main`, `rt_dispatch` and `rt_finalize`:
///
/// - `APPRUNTIME_LINKED_PRODUCT`: `ExampleApp` (the default), `ExampleUI`,
///   `ExampleWeb`, whose browser engine the test stands in for,
///   `ExampleFiles`, which keeps real files in a temporary directory,
///   `ExampleDocuments`, whose pickers the test answers, over real files,
///   `ExampleNotifications`, whose notification centre the test keeps,
///   `ExampleBackground`, whose tasks the test runs as the system would,
///   `ExampleMedia`, whose players the test stands in for,
///   `ExampleText`, whose text views are texts the test types into,
///   `ExampleClipboard`, whose clipboard the test keeps,
///   `ExampleTransfers`, whose server and system the test plays,
///   `ExampleNotes`, whose window the test reports,
///   `ExampleSignIn`, whose browser the test plays, with its secrets in
///   memory,
///   `ExampleCalendar`, whose events are in a store in memory,
///   `ExampleContacts`, whose address book is in memory,
///   `ExampleCamera`, whose cameras the test stands in for, saving to a
///   photo library in memory,
///   `ExamplePhotos`, whose photo library is in memory, over real files,
///   `ExampleDefaults`, whose settings are kept in a real file,
///   `ExampleModel`, whose store is CoreModel's in-memory backend, or
///   `ExampleGL`, which draws: the test host's GL is `CFakeGL`, which
///   writes down what it's asked.
/// - `APPRUNTIME_LINKED_ENGINE`:
///   - `slice` (the default): the sealed macOS slice, from
///     `Scripts/guest.py slice --product <product> --target macos`;
///   - `wasm2c`: `App.wasm` translated to C, from `Scripts/build-wasm.sh
///     <product>` and `Scripts/wasm2c-shim.py build --wasm
///     .build/guest/<product>/wasm32/App.wasm --output
///     .build/guest/<product>/wasm2c`.
///
/// Without the library, the test target builds without it, and its tests are
/// skipped.
let environment = ProcessInfo.processInfo.environment
let product = environment["APPRUNTIME_LINKED_PRODUCT"] ?? "ExampleApp"
let engine = environment["APPRUNTIME_LINKED_ENGINE"] ?? "slice"
let library = URL(fileURLWithPath: Context.packageDirectory)
    .appendingPathComponent("../../.build/guest/\(product)/\(engine == "wasm2c" ? "wasm2c" : "macos")/libapp.a")
    .standardizedFileURL.path
let linked = FileManager.default.fileExists(atPath: library)

let package = Package(
    name: "LinkedSlice",
    platforms: [
        .macOS(.v12),
    ],
    dependencies: [
        .package(name: "AppRuntime", path: "../..", traits: []),
    ],
    targets: [
        // Generated by Scripts/gles2.py: every gl* function, as a GL library
        // has, so a library that draws links.
        .target(
            name: "CFakeGL",
            dependencies: [.product(name: "CGLES2", package: "AppRuntime")],
            path: "Tests/CFakeGL"
        ),
        .testTarget(
            name: "LinkedSliceTests",
            dependencies: [
                "CFakeGL",
                .product(name: "DynamicGraphics", package: "AppRuntime"),
                .product(name: "DynamicWebKit", package: "AppRuntime"),
                .product(name: "DynamicFiles", package: "AppRuntime"),
                .product(name: "DynamicDocuments", package: "AppRuntime"),
                .product(name: "RuntimeDocuments", package: "AppRuntime"),
                .product(name: "DynamicNotifications", package: "AppRuntime"),
                .product(name: "RuntimeNotifications", package: "AppRuntime"),
                .product(name: "DynamicBackgroundTasks", package: "AppRuntime"),
                .product(name: "RuntimeBackgroundTasks", package: "AppRuntime"),
                .product(name: "DynamicText", package: "AppRuntime"),
                .product(name: "RuntimeText", package: "AppRuntime"),
                .product(name: "DynamicClipboard", package: "AppRuntime"),
                .product(name: "DynamicTransfers", package: "AppRuntime"),
                .product(name: "RuntimeTransfers", package: "AppRuntime"),
                .product(name: "RuntimeClipboard", package: "AppRuntime"),
                .product(name: "DynamicSecrets", package: "AppRuntime"),
                .product(name: "RuntimeSecrets", package: "AppRuntime"),
                .product(name: "DynamicAuthentication", package: "AppRuntime"),
                .product(name: "RuntimeAuthentication", package: "AppRuntime"),
                .product(name: "DynamicCalendar", package: "AppRuntime"),
                .product(name: "RuntimeCalendar", package: "AppRuntime"),
                .product(name: "DynamicContacts", package: "AppRuntime"),
                .product(name: "RuntimeContacts", package: "AppRuntime"),
                .product(name: "DynamicPhotos", package: "AppRuntime"),
                .product(name: "RuntimePhotos", package: "AppRuntime"),
                .product(name: "DynamicCamera", package: "AppRuntime"),
                .product(name: "RuntimeCamera", package: "AppRuntime"),
                .product(name: "DynamicMedia", package: "AppRuntime"),
                .product(name: "RuntimeMedia", package: "AppRuntime"),
                .product(name: "DynamicDefaults", package: "AppRuntime"),
                .product(name: "DynamicCoreModel", package: "AppRuntime"),
                .product(name: "RuntimeCoreModel", package: "AppRuntime"),
                .product(name: "RuntimeHost", package: "AppRuntime"),
                .product(name: "CRuntime", package: "AppRuntime"),
                .product(name: "DynamicRuntime", package: "AppRuntime"),
                .product(name: "DynamicUI", package: "AppRuntime"),
                .product(name: "RuntimeABI", package: "AppRuntime"),
                .product(name: "RuntimeCore", package: "AppRuntime"),
                .product(name: "RuntimeNative", package: "AppRuntime"),
                .product(name: "ExampleContracts", package: "AppRuntime"),
                .product(name: "ExampleHost", package: "AppRuntime"),
            ],
            swiftSettings: linked ? [.define("LINKED_SLICE"), .define("LINKED_\(product.uppercased())")] : [],
            linkerSettings: linked ? [.unsafeFlags([library])] : []
        ),
    ]
)
